"""Pak128 objects for every counted vehicle: assets/pak_map.json and pak_request.md (the list for the VZ pak session).

  python 04b_pak.py --state 2026-09-29                          trolleybus sheet
  python 04b_pak.py --state 2026-09-29 --base ../../plzen-bus   bus sheet

Naming follows the VZ pak session's scheme (as for VZ-PMDP-tram, VZ-DPBrno-trolleybus and VZ-DPBrno-bus):
  VZ-PMDP-<type token>-<livery slug>-<core>, in the package state["pak"]["package"] (VZ-PMDP-trolleybus / VZ-PMDP-bus);
  another operator's vehicles (subcontractors) go to the shared city package VZ-Plzen-bus with the same scheme, never
  to a PMDP or other-city stand-in (user rule, Prague bus sheet, 29 Sep 2026).
  Articulated: two objects built as one vehicle; trolleybuses <core> + <core>-B (VZ-DPBrno-trolleybus 27Tr),
  buses <core>-A + <core>-B (VZ-DPBrno-bus Urbino_18).
Liveries: the register's paint -> a slug (state pak.liveries). An advert wrap (CVR ...) or any other paint maps to the
type's normal livery: the most common own livery of that operator's cars of the type (the pak session's rule).
Status: "installed" when every object name is found in a .dat under <pak checkout>/build/, else "requested".
The pak checkouts are read only (C:/Users/vojte/Developer/simutrans-custom-czech-pak128*); nothing is sent anywhere.
"""
import argparse, collections, glob, os, re
from common import BASE, DER as TDER, state, load, save

p = argparse.ArgumentParser(); p.add_argument('--state', required=True); p.add_argument('--base', default=BASE); a = p.parse_args()
base = os.path.abspath(a.base); S = state(a.state, base); PK = S['pak']; DER = os.path.join(base, 'data', 'derived')
FL = load(os.path.join(DER, S['name'], 'fleet.json'))
veh = load(os.path.join(TDER, f"vehicles_{S['register_date']}.json"))
units = [u for o in FL['lines'].values() for u in o if not u.get('spare')]

# object names in the local pak checkouts
names, heads = set(), []
for root in PK.get('checkouts', []):
    for fn in glob.glob(os.path.join(root, 'build', '*', '*.dat')):
        for line in open(fn, encoding='utf-8', errors='replace'):
            if line.lower().startswith('name='): names.add(line.split('=', 1)[1].strip())
    g = os.path.join(root, '.git')
    if os.path.isfile(g): g = open(g).read().split('gitdir:', 1)[1].strip()        # a worktree: .git is a file
    hd = os.path.join(g, 'HEAD')
    if os.path.exists(hd): heads.append(os.path.basename(root) + ' ' + open(hd).read().strip().split('/')[-1][:12])

def slug_of(liv):
    for k, s in PK['liveries'].items():
        if liv.startswith(k): return s
    return None
own = collections.defaultdict(collections.Counter)          # (operator, type) -> own livery slugs over the whole register
for v in veh.values():
    s = slug_of(v.get('livery', ''))
    if s: own[(v.get('operator'), v.get('type'))][s] += 1

def pak_for(u):
    t = PK['types'].get(u['type'])
    if not t: return None
    s = slug_of(u['livery']); why = ''
    if not s:
        c = own.get((u['operator'], u['type']))
        s = c.most_common(1)[0][0] if c else PK['default_livery']
        why = 'advert wrap' if u['livery'].startswith('CVR') else 'livery not in the pak'
    pkg = PK['package'] if u['operator'] == 'PMDP' else PK['other_package']
    stem = f"{pkg.rsplit('-', 1)[0]}-{t['token']}-{s}-{t['core']}"
    if t.get('articulated'):
        objs = [stem, stem + '-B'] if PK['articulated_style'] == 'B' else [stem + '-A', stem + '-B']
    else: objs = [stem]
    return dict(key=f"{u['operator']}|{u['type']}|{s}", package=pkg, objs=objs, core=t['core'], livery=s, mapped=why, m=t['m'], len=t['len'],
                status='installed' if all(o in names for o in objs) else 'requested')

pmap, req, by_car = {}, collections.defaultdict(list), {}
for o in FL['lines'].values():
    for u in o:
        x = pak_for(u)
        if not x: continue
        pmap[x['key']] = {k: v for k, v in x.items() if k != 'key' and k != 'mapped'}
        by_car[u['id']] = x['key']
        if not u.get('spare'): req[x['key']].append((u['car'], u['livery'], x['mapped']))
# the pak core shows the livery only where the pak has more than one livery object for the type
per_type = collections.Counter((k.split('|')[0], k.split('|')[1]) for k in pmap)
for k, x in pmap.items():
    op, ty, s = k.split('|'); x['core_shown'] = x['core'] + (f" {PK['livery_names'].get(s, s)}" if per_type[(op, ty)] > 1 else '')
save(dict(_source='VZ pak session objects, checked against ' + (', '.join(heads) or 'no local checkout') +
          '. Status "requested" = not yet in any local pak build; the name is the one asked for in pak_request.md.', objects=pmap, by_car=by_car),
     os.path.join(base, 'assets', 'pak_map.json'))

# pak_request.md
L = [f"# Pak request: {S['title']} ({S['name']})", '',
     f"For the VZ pak session (simutrans-custom-czech-pak128). Generated by 04b_pak.py from the vehicles counted on the sheet "
     f"(vehicle day {S['vehicles_date']}). Local pak build checked: {', '.join(heads) or 'none'}.", '',
     PK['request_intro'], '',
     '| Object(s) | Type | Livery (real → object) | Operator | Length | Car units | Cars in the peak | Status |', '|---|---|---|---|---|---|---|---|']
for k in sorted(req, key=lambda k: (k.split('|')[0] != 'PMDP', k)):
    x = pmap[k]; op, ty, s = k.split('|'); cars = req[k]
    real = collections.Counter(l for _, l, _ in cars)
    lv = '; '.join(f"{n}× {l}" for l, n in real.most_common()) + f" → {s}" + (' (advert wraps mapped to the normal livery)' if any(m for _, _, m in cars) else '')
    nums = ', '.join(sorted({c for c, _, _ in cars}, key=lambda c: (len(c), c)))
    L.append(f"| {' + '.join(x['objs'])} | {ty} | {lv} | {op} | {x['m']} m | {x['len']} | {len(cars)}: {nums} | {x['status']} |")
L += ['', PK.get('request_notes', '')]
open(os.path.join(base, 'pak_request.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('pak', len(pmap), 'objects;', collections.Counter(x['status'] for x in pmap.values()), '-> assets/pak_map.json, pak_request.md')
